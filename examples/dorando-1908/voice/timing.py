# Lay the lines end to end with their pauses -> voice.wav + ../src/d/timing.ts ([start, end] frame of each line)
import os, json, numpy as np, soundfile as sf
from lines import LINES, PAUSE
H = os.path.dirname(os.path.abspath(__file__)); SR = 48000; t = 0.15; parts = []; table = []
for i in range(len(LINES)):
    y, _ = sf.read(f"{H}/seg_J/{i:02d}.wav"); table.append([round(t * 30), round((t + len(y) / SR) * 30)]); parts.append((t, y)); t += len(y) / SR + PAUSE[i]
total = round((t + 1.4) * 30); out = np.zeros(int(total / 30 * SR) + SR)
for t0, y in parts: j = int(t0 * SR); out[j:j + len(y)] += y
out = out[: int(total / 30 * SR)]; sf.write(f"{H}/voice.wav", out / np.max(np.abs(out)) * 0.89, SR)
open(f"{H}/../src/d/timing.ts", "w").write("// generated by voice_d/timing.py: [start, end] frame of each narrated line\nexport const LINES: [number, number][] = " + json.dumps(table) + ";\nexport const TOTAL = %d;\n" % total)
print(total, total / 30, table)
