# Guide narration (neural voice) -> guide.wav + src/c/timing.ts (line start/end frames). The picture is timed to this table;
# when the real narration arrives, fit.py rewrites the same table from the recording.
import sys, os, subprocess, json, numpy as np, soundfile as sf
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lines import LINES
HERE = os.path.dirname(os.path.abspath(__file__)); SR = 48000
voice = sys.argv[1] if len(sys.argv) > 1 else "es-ES-AlvaroNeural"; rate = sys.argv[2] if len(sys.argv) > 2 else "+6%"
os.makedirs(f"{HERE}/seg_guide", exist_ok=True)
def clip(i, text):
    mp3 = f"{HERE}/seg_guide/{i:02d}.mp3"; wav = mp3.replace(".mp3", ".wav")
    if not os.path.exists(wav):
        for k in range(4):
            r = subprocess.run([sys.executable, f"{HERE}/edge_one.py", voice, rate, mp3, text.replace("«", "").replace("»", "")])
            if r.returncode == 0 and os.path.exists(mp3) and os.path.getsize(mp3) > 2000: break
            import time; time.sleep(3 + 4 * k)
        else: raise SystemExit('voice service failed on line %d' % i)
        af = "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.02,areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.03,areverse"
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", mp3, "-af", af, "-ar", str(SR), "-ac", "1", wav], check=True)
    a, _ = sf.read(wav); return a
t = 0.12; parts = []; table = []
for i, (text, gap) in enumerate(LINES):
    a = clip(i, text); table.append([round(t * 30), round((t + len(a) / SR) * 30)]); parts.append((t, a)); t += len(a) / SR + gap
total = round((t + 1.6) * 30)
mix = np.zeros(int(total / 30 * SR))
for t0, a in parts: j = int(t0 * SR); mix[j:j + len(a)] += a
sf.write(f"{HERE}/guide.wav", mix / np.max(np.abs(mix)) * 0.89, SR)
open(f"{HERE}/../src/k/timing.ts", "w").write("// generated by voice_p (guide.py / fit.py): [start, end] frame of each narrated line\nexport const LINES: [number, number][] = " + json.dumps(table) + ";\nexport const TOTAL = %d;\n" % total)
words = sum(len(x[0].split()) for x in LINES)
print("total frames", total, "=", total / 30, "s;", words, "words"); print(table)
