# Fit the picture to a real narration: find where each script line starts/ends in the recording (DTW against the guide
# narration, whose line times are known), tighten long pauses, and rewrite src/c/timing.ts.
# usage: python3 fit.py <recording or processed voice.wav> [max_gap_s]   ->  voice_fit.wav, fit.json, ../src/c/timing.ts
import sys, os, json, re, subprocess, numpy as np, soundfile as sf, librosa
HERE = os.path.dirname(os.path.abspath(__file__)); SR = 48000
src = sys.argv[1]; MAXGAP = float(sys.argv[2]) if len(sys.argv) > 2 else 0.45
def load16(path):
    tmp = HERE + "/_tmp16.wav"; subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", path, "-ar", "16000", "-ac", "1", tmp], check=True); a, _ = sf.read(tmp); os.remove(tmp); return a
def feats(a):
    m = librosa.feature.mfcc(y=a, sr=16000, n_mfcc=20, hop_length=160, n_fft=400)[1:]; d = librosa.feature.delta(m)
    x = np.vstack([m, d]); return (x - x.mean(1, keepdims=True)) / (x.std(1, keepdims=True) + 1e-6)
# guide line times: recompute from the guide clips so they do not depend on the current timing.ts
sys.path.insert(0, HERE); from lines import LINES as TXT
g = load16(HERE + "/guide.wav"); t = 0.12; GL = []
for i, (_, gap) in enumerate(TXT):
    a, sr = sf.read(f"{HERE}/seg_guide/{i:02d}.wav"); GL.append((t, t + len(a) / sr)); t += len(a) / sr + gap
r = load16(src)
D, wp = librosa.sequence.dtw(X=feats(g), Y=feats(r), metric="cosine", subseq=False)
wp = wp[::-1]; gi, ri = wp[:, 0] * 0.01, wp[:, 1] * 0.01
def to_rec(tg): return float(np.median(ri[np.abs(gi - tg) < 0.012])) if np.any(np.abs(gi - tg) < 0.012) else float(np.interp(tg, gi, ri))
# energy envelope of the recording for snapping to the nearest pause edge
e = librosa.feature.rms(y=r, frame_length=400, hop_length=160)[0]; thr = max(np.percentile(e, 95) * 0.06, 1e-4); loud = e > thr
def snap_start(tr, lo, hi):
    i0, i1 = int(max(lo, tr - 0.35) * 100), int(min(hi, tr + 0.35) * 100); best = None
    for i in range(max(1, i0), min(len(loud) - 1, i1)):
        if loud[i] and not loud[i - 3:i].any():
            if best is None or abs(i - tr * 100) < abs(best - tr * 100): best = i
    return (best if best is not None else int(tr * 100)) / 100
def snap_end(tr, lo, hi):
    i0, i1 = int(max(lo, tr - 0.35) * 100), int(min(hi, tr + 0.35) * 100); best = None
    for i in range(max(1, i0), min(len(loud) - 4, i1)):
        if loud[i] and not loud[i + 1:i + 4].any():
            if best is None or abs(i - tr * 100) < abs(best - tr * 100): best = i
    return ((best if best is not None else int(tr * 100)) + 1) / 100
raw = [(to_rec(a), to_rec(b)) for a, b in GL]; dur = len(r) / 16000; seg = []
for k, (a, b) in enumerate(raw):
    lo = seg[-1][1] if seg else 0.0; hi = raw[k + 1][0] + 0.2 if k + 1 < len(raw) else dur
    s = snap_start(a, lo, hi); en = snap_end(b, s + 0.2, hi + 0.2 if k + 1 < len(raw) else dur); seg.append((s, max(en, s + 0.2)))
# rebuild the narration: each line as recorded, pauses clipped to MAXGAP (never shorter than 0.18 s)
full, fsr = sf.read(src)
if full.ndim > 1: full = full.mean(1)
if fsr != SR: full = librosa.resample(full, orig_sr=fsr, target_sr=SR)
out = []; table = []; t = 0.12; out.append(np.zeros(int(t * SR)))
for k, (s, en) in enumerate(seg):
    a = full[int(max(0, s - 0.03) * SR):int((en + 0.05) * SR)].copy(); n = int(0.02 * SR); a[:n] *= np.linspace(0, 1, n); a[-n:] *= np.linspace(1, 0, n)
    table.append([round((t + 0.03) * 30), round((t + len(a) / SR - 0.05) * 30)]); out.append(a); t += len(a) / SR
    if k + 1 < len(seg): gap = min(MAXGAP, max(0.18, seg[k + 1][0] - en)) - 0.08; out.append(np.zeros(int(max(0.05, gap) * SR))); t += max(0.05, gap)
total = round((t + 1.0) * 30); v = np.concatenate(out + [np.zeros(SR)])
sf.write(HERE + "/voice_fit.wav", v / (np.max(np.abs(v)) + 1e-9) * 0.89, SR)
json.dump({"segments_in_recording": seg, "lines": table, "total": total}, open(HERE + "/fit.json", "w"), indent=1)
if "--dry" not in sys.argv:
    open(HERE + "/../src/c/timing.ts", "w").write("// generated by voice_p (guide.py / fit.py): [start, end] frame of each narrated line\nexport const LINES: [number, number][] = " + json.dumps(table) + ";\nexport const TOTAL = %d;\n" % total)
print("total", total, "frames =", round(total / 30, 2), "s"); print("segments", [(round(a, 2), round(b, 2)) for a, b in seg])
